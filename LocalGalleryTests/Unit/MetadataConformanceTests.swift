/// Pins the metadata reader's output over the adversarial asset tree in
/// `core/fixtures/scan-conformance/assets/`.
///
/// Generated from the shipping Swift `MetadataReader`; now run against the Rust
/// `gallery-meta` read side through the FFI, with **every assertion and every
/// note unchanged**. `core/gallery-meta/tests/metadata_conformance.rs` checks
/// the same file on the host; this one checks that the *bridge* — the
/// device-zone resolution of the core's zone-less wall clock, the Unix-seconds
/// video date — lands on the same values the Swift reader produced.
///
/// The `notes` on each entry are part of the fixture on purpose — they are the
/// only place several of these behaviours are written down.
///
/// Assets are built by `scripts/gen_conformance_assets.py`; the expectation
/// file is regenerated by running this suite with `CONFORMANCE_REGEN=1`.
final class MetadataConformanceTests: XCTestCase {

    // MARK: - Fixture shape

    struct Dump: Codable, Equatable {
        /// Bump when the *shape* of an entry changes (not when a value moves).
        let schema: Int
        let files: [Entry]
    }

    struct Entry: Codable, Equatable {
        /// Path relative to `assets/`, `/`-separated. Sorted, so the file is
        /// stable regardless of directory-enumeration order.
        let path: String
        /// How the scan pipeline classifies the file by extension:
        /// `image` / `video` / `skipped` (the scanner never opens the last).
        let scannerKind: String
        /// A `<name>.xmp` sits next to it.
        let hasSidecar: Bool
        /// `readImageMetadata` — run for every entry including
        /// videos and `skipped` files, to pin what the reader *would* return.
        let dateTaken: ConformanceDate?
        let countryCode: String?
        let gpsLatitude: Double?
        let gpsLongitude: Double?
        let hierarchicalTags: [ConformanceTag]
        let faceRegions: [ConformanceRegion]
        /// `readVideoDate` — run only for `video` entries.
        let videoDate: ConformanceDate?
        /// Behaviour this entry exists to pin. Asserted like everything else.
        let notes: [String]
    }

