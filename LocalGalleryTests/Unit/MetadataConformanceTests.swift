    func testMetadataConformance() async throws {
        let assets = try ConformanceFixtures.assets()
        let files = try Self.assetFiles(under: assets)
        XCTAssertGreaterThanOrEqual(files.count, 50, "the asset tree looks truncated")

        var entries: [Entry] = []
        for relativePath in files {
            let url = assets.appendingPathComponent(relativePath)
            let ext = url.pathExtension.lowercased()
            let type = ext.isEmpty ? nil : UTType(filenameExtension: ext)
            let isImage = type?.conforms(to: .image) ?? false
            let isVideo = type?.conforms(to: .movie) ?? false
            let kind = isVideo ? "video" : (isImage ? "image" : "skipped")

            let metadata = readImageMetadata(path: url.path)
            // The bridge, exercised: the core hands back a zone-less wall
            // clock and the app resolves it in the device zone, which is what
            // `exifDateFormatter` did by having no `timeZone` at all.
            let captureDate = metadata.captureWallClock.flatMap(EnrichmentService.resolve)
            let videoDate = isVideo
                ? readVideoDate(path: url.path)
                    .map { Date(timeIntervalSince1970: TimeInterval($0)) }
                : nil

            entries.append(Entry(
                path: relativePath,
                scannerKind: kind,
                hasSidecar: FileManager.default.fileExists(
                    atPath: url.appendingPathExtension("xmp").path
                ),
                dateTaken: ConformanceDate.localWallClock(captureDate),
                countryCode: metadata.countryCode,
                gpsLatitude: metadata.gpsLatitude,
                gpsLongitude: metadata.gpsLongitude,
                hierarchicalTags: metadata.hierarchicalTags.map {
                    ConformanceTag(HierarchicalTag(fullPath: $0.fullPath, namespace: $0.namespace,
                                                   displayName: $0.displayName))
                },
                faceRegions: metadata.faceRegions.map {
                    ConformanceRegion(FaceRegion(name: $0.name, centerX: $0.centerX,
                                                 centerY: $0.centerY, width: $0.width,
                                                 height: $0.height))
                },
                videoDate: ConformanceDate.utc(videoDate),
                notes: Self.notes[relativePath] ?? []
            ))
        }

        try ConformanceFixtures.assertMatches(
            Dump(schema: 1, files: entries),
            fixture: "metadata_conformance.json"
        )
    }

    /// Every annotated path must exist, so a renamed asset can't leave its
    /// notes orphaned and silently unenforced.
    func testEveryAnnotatedPathExists() throws {
        let assets = try ConformanceFixtures.assets()
        let present = Set(try Self.assetFiles(under: assets))
        for path in Self.notes.keys.sorted() {
            XCTAssertTrue(present.contains(path), "annotated asset \(path) is missing from the tree")
        }
    }

    func testCommittedFixtureIsCanonical() throws {
        try ConformanceFixtures.assertCommittedBytesAreCanonical(
            Dump.self, fixture: "metadata_conformance.json"
        )
    }

    // MARK: - Enumeration

    /// Relative, `/`-separated paths of every asset that is *not* a sidecar,
    /// sorted. `.xmp` files are inputs to the merge, reported via `hasSidecar`.
    static func assetFiles(under root: URL) throws -> [String] {
        let fm = FileManager.default
        guard let walker = fm.enumerator(at: root, includingPropertiesForKeys: [.isRegularFileKey]) else {
            return []
        }
        var out: [String] = []
        let prefix = root.standardizedFileURL.path + "/"
        for case let url as URL in walker {
            let values = try url.resourceValues(forKeys: [.isRegularFileKey])
            guard values.isRegularFile == true else { continue }
            let name = url.lastPathComponent
            if name == ".DS_Store" { continue }
            if url.pathExtension.lowercased() == "xmp" { continue }
            let path = url.standardizedFileURL.path
            guard path.hasPrefix(prefix) else { continue }
            out.append(String(path.dropFirst(prefix.count)))
        }
        return out.sorted()
    }
